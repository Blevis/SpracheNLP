"""Generate the data-dependent parts of the LaTeX report (docs/generated/).

docs/report.tex holds the hand-written prose and \\input's these files, so
every number and table in the PDF comes from the current corpus and model:

    numbers.tex        \\newcommand macros (\\NTexts, \\NTokens, ...)
    tab_*.tex          booktabs tables
    dep_sentenceN.tex  tikz-dependency trees of the pinned sentences
    sources.tex        longtable with all sources (appendix)

Build: ``python -m sprache report`` (add ``--pdf`` to compile with LuaLaTeX).
"""
from __future__ import annotations

import shutil
import subprocess
from collections import Counter
from pathlib import Path

import pandas as pd

from . import analysis, clean, config, corpus, quality, stats

DOCS = config.ROOT / "docs"
GEN = DOCS / "generated"

_TEX_ESC = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
            "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
            "[": "{[}", "]": "{]}"}


def esc(text) -> str:
    s = "".join(_TEX_ESC.get(c, c) for c in str(text))
    return s.replace("--", "-{}-")          # stop TeX turning spaCy's "--" lemma into a dash


def _fmt(n) -> str:
    return f"{n:,}".replace(",", "{,}") if isinstance(n, int) else str(n)


def _write(name: str, body: str) -> Path:
    GEN.mkdir(parents=True, exist_ok=True)
    p = GEN / name
    p.write_text("% generated by `python -m sprache report` - do not edit\n" + body, encoding="utf-8")
    return p


def _table(df: pd.DataFrame, spec: str, header: list[str], mono_cols=()) -> str:
    rows = []
    for r in df.itertuples(index=False):
        cells = [rf"\texttt{{{esc(v)}}}" if i in mono_cols else esc(v) for i, v in enumerate(r)]
        rows.append(" & ".join(cells) + r" \\")
    return (rf"\begin{{tabular}}{{{spec}}}\toprule" + "\n" + " & ".join(header) + r" \\\midrule" + "\n"
            + "\n".join(rows) + "\n" + r"\bottomrule\end{tabular}" + "\n")


def _dependency(doc, scale: float = 1.0) -> str:
    """tikz-dependency code for one parsed sentence (tokens, POS row, arcs, root)."""
    toks = list(doc)
    words = r" \& ".join(esc(t.text) for t in toks)
    tags = r" \& ".join(rf"\textsc{{{esc(t.pos_.lower())}}}" for t in toks)
    lines = [r"\begin{dependency}[theme=simple, label style={font=\scriptsize}, edge style={thin}]",
             r"\begin{deptext}[column sep=0.25em, font=\small]", words + r" \\", tags + r" \\",
             r"\end{deptext}"]
    for t in toks:
        if t.dep_ == "ROOT":
            lines.append(rf"\deproot{{{t.i + 1}}}{{ROOT}}")
        else:
            lines.append(rf"\depedge{{{t.head.i + 1}}}{{{t.i + 1}}}{{{esc(t.dep_)}}}")
    lines.append(r"\end{dependency}")
    return (rf"\resizebox{{{scale}\linewidth}}{{!}}{{%" + "\n" + "\n".join(lines) + "\n}\n")


def generate() -> list[Path]:
    nlp = analysis.load_model()
    sw = nlp.Defaults.stop_words
    raw, cl = corpus.load(config.CORPUS_RAW), corpus.load(config.CORPUS_CLEAN)
    src = pd.DataFrame(corpus.read_sources())
    src["words"] = src.words.astype(int)
    skipped = pd.read_csv(config.SKIPPED_CSV)
    docs_raw, docs_cl = stats.parse(nlp, raw), stats.parse(nlp, cl)
    st, stc = stats.compute(docs_raw, sw), stats.compute(docs_cl, sw)
    topic_of = dict(zip(src.file, src.topic))
    pt = stats.per_topic(docs_raw, topic_of, sw)
    hits: Counter = Counter()
    for t in raw.values():
        clean.clean_text(t, hits)
    rep_raw, rep_cl = quality.pattern_report(raw), quality.pattern_report(cl)
    out = []

    # ---- numbers
    others = pt.ttr.drop("Städte")
    macros = {
        "NTexts": st.texts, "NTopics": src.topic.nunique(), "NWords": int(src.words.sum()),
        "MinWords": int(src.words.min()), "MedWords": int(src.words.median()), "MaxWords": int(src.words.max()),
        "NTokens": st.tokens, "NWordTokens": st.word_tokens, "NUnique": st.unique_words,
        "NLemmas": st.unique_lemmas, "TTR": f"{st.ttr:.2f}", "NSents": st.sentences,
        "TokPerSent": f"{st.tokens_per_sentence:.1f}", "StopShare": f"{st.stopword_share * 100:.1f}\\%",
        "NCandidates": len(src) + len(skipped), "NSkipped": len(skipped),
        "NSkippedShort": int(skipped.reason.str.startswith("only").sum()),
        "NSkippedMax": int((skipped.reason == "MAX_TEXTS reached").sum()),
        "NChanged": sum(1 for t in raw.values() if clean.clean_text(t) != t),
        "TokRemoved": st.tokens - stc.tokens,
        "TokRemovedPct": f"{(st.tokens - stc.tokens) / st.tokens * 100:.1f}\\%",
        "NIPAFiles": int(rep_raw.set_index("check").loc["IPA transcription"].files_affected),
        "TTRCity": f"{pt.ttr['Städte']:.2f}", "TTROtherMin": f"{others.min():.2f}",
        "TTROtherMax": f"{others.max():.2f}", "Retrieved": src.retrieved.iloc[0],
        "SpacyVersion": __import__("spacy").__version__, "ModelVersion": nlp.meta["version"],
        "ModelName": esc(config.SPACY_MODEL), "Licence": esc(config.LICENCE),
    }
    out.append(_write("numbers.tex", "".join(
        rf"\newcommand{{\{k}}}{{{_fmt(v) if isinstance(v, int) else v}}}" + "\n" for k, v in macros.items())))

    # ---- statistics
    ov = stats.compare(st, stc).reset_index()
    out.append(_write("tab_overview.tex", _table(ov, "lrr", ["Measure", "Raw", "Clean"])))
    top = stats.top_table(st, 10, sw).reset_index()[["rank", "word", "count", "share", "content_word", "content_count"]]
    out.append(_write("tab_top10.tex", _table(top, "rlrrlr",
                                              ["\\#", "Word", "Count", "Share", "Content word", "Count"], mono_cols=(1, 4))))
    ptab = pt.reset_index()[["topic", "texts", "word_tokens", "unique_words", "ttr", "top_content_words"]]
    out.append(_write("tab_topics.tex", _table(ptab, r"lrrrr>{\raggedright\arraybackslash}p{5.2cm}",
                                               ["Topic", "Texts", "Words", "Types", "TTR", "Top content words"])))
    # ---- quality
    q = rep_raw[["check", "files_affected", "occurrences"]].merge(
        rep_cl[["check", "files_affected", "occurrences"]], on="check")
    out.append(_write("tab_quality.tex", _table(q, "lrrrr",
                                                ["Check", "Files (raw)", "Hits (raw)", "Files (clean)", "Hits (clean)"])))
    rules = pd.DataFrame([(name, rx.pattern, hits.get(name, 0)) for name, rx, _ in clean.RULES],
                         columns=["rule", "pattern", "hits"]).drop_duplicates("rule")
    rules["pattern"] = rules.pattern.str.slice(0, 48)
    out.append(_write("tab_rules.tex", _table(rules[["rule", "hits"]], "lr", ["Rule", "Hits"], mono_cols=(0,))))
    examples = pd.DataFrame([(f, raw[f][:95] + "…", cl[f][:80] + "…") for f in ("text041.txt", "text054.txt", "text008.txt")],
                            columns=["file", "raw", "clean"])
    out.append(_write("tab_clean_examples.tex", _table(examples, r"l>{\raggedright\arraybackslash}p{6.6cm}>{\raggedright\arraybackslash}p{5.6cm}", ["File", "Raw", "Clean"])))

    # ---- sentences
    for i, s in enumerate(config.PINNED_SENTENCES, 1):
        d = nlp(s)
        tt = analysis.token_table(d).reset_index()[["token", "lemma", "pos", "tag", "dep", "head", "ent"]]
        out.append(_write(f"tab_sentence{i}.tex", _table(tt, "lllllll",
                                                         ["Token", "Lemma", "POS", "Tag", "Dep", "Head", "Ent"])))
        out.append(_write(f"dep_sentence{i}.tex", _dependency(d)))
    out.append(_write("dep_demo.tex", _dependency(nlp(config.DEMO_SENTENCE), 0.85)))
    d1c = nlp(clean.clean_text(config.PINNED_SENTENCES[0]))
    out.append(_write("dep_sentence1_clean.tex", _dependency(d1c)))

    # ---- German-specific
    pr = analysis.probe_table(nlp)[["input", "n_tokens", "lemmas", "pos"]]
    out.append(_write("tab_probes.tex", _table(pr, r">{\raggedright\arraybackslash}p{4.2cm}r>{\raggedright\arraybackslash}p{4.4cm}>{\raggedright\arraybackslash}p{3.6cm}", ["Input", "Tok.", "Lemmas", "POS"])))
    lw = analysis.longest_words(docs_raw, 8)[["word", "length", "pos"]]
    out.append(_write("tab_longest.tex", _table(lw, "lrl", ["Word", "Len.", "POS"])))
    con = analysis.contraction_lemmas(docs_raw)
    con["lemma/tag (top 3)"] = con["lemma/tag (top 3)"].map(lambda d: ", ".join(f"{k} ({v})" for k, v in d.items()))
    out.append(_write("tab_contractions.tex", _table(con, "lrl", ["Form", "Count", "Lemma/tag (count)"], mono_cols=(0,))))

    # ---- table row + sources
    row = pd.DataFrame([("Language", "German"), ("Source", "de.wikipedia.org (article introductions, 8 topics)"),
                        ("Licence", config.LICENCE), ("Texts", st.texts), ("Tokens", f"{st.tokens:,}"),
                        ("Word tokens", f"{st.word_tokens:,}"), ("Unique words", f"{st.unique_words:,}"),
                        ("Problems found", quality.summary(raw))], columns=["k", "v"])
    out.append(_write("tab_row.tex", _table(row, r"l>{\raggedright\arraybackslash}p{10.5cm}", ["Field", "Group 2"])))
    lines = [rf"\texttt{{{esc(r.file)}}} & {esc(r.title)} & {esc(r.topic)} & {r.words} & "
             rf"\href{{{r.permalink}}}{{{r.revision_id}}} & {r.last_modified} \\"
             for r in src.itertuples()]
    out.append(_write("sources.tex",
        r"\begin{longtable}{lp{4.4cm}p{3.6cm}rll}\toprule" + "\n"
        r"File & Title & Topic & Words & Revision & Modified \\\midrule\endhead" + "\n"
        + "\n".join(lines) + "\n" + r"\bottomrule\end{longtable}" + "\n"))
    return out


def compile_pdf() -> Path:
    exe = shutil.which("lualatex")
    if not exe:
        raise RuntimeError("lualatex not found; install MiKTeX or TeX Live, or compile docs/report.tex on Overleaf")
    for _ in range(3):                       # later runs resolve references, ToC and longtable widths
        subprocess.run([exe, "-interaction=nonstopmode", "-halt-on-error", "report.tex"],
                       cwd=DOCS, check=True, stdout=subprocess.DEVNULL)
    return DOCS / "report.pdf"
